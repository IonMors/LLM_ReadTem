
import httpx

from deepteam.test_case import RTTurn


TARGET_URL = "http://127.0.0.1:8000/chat"

'''
RTTurn is a data structure provided by DeepTeam that represents a single message (turn) in a conversation during red-team testing.
turns = [
    RTTurn(role="user", content="Hello"),
    RTTurn(role="assistant", content="How can I help you?"),
]
'''
async def model_callback(
    input: str,
    turns: list[RTTurn] | None = None,
) -> str:
    """
    Send DeepTeam's adversarial input to our target chatbot.

    Args:
        input: Adversarial prompt generated by DeepTeam.
        turns: Optional conversation history for multi-turn attacks.

    Returns:
        The target application's response as a string.
    """

    messages = []

    if turns:
        for turn in turns:
            messages.append({
                "role": turn.role,
                "content": turn.content,
            })

    messages.append({
        "role": "user",
        "content": input,
    })

    # Our current target API accepts a single message.
    # Multi-turn history will be supported in a later milestone.
    payload = {"message": input}

    async with httpx.AsyncClient(timeout=60.0) as client:
        response = await client.post(
            TARGET_URL,
            json=payload,
        )

        response.raise_for_status()

        data = response.json()

        return data["response"]
